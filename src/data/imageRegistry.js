export const getDestinationImage = (destinationId, customPhotos = null) => {
  // 1. User custom photo priority
  if (customPhotos && customPhotos[destinationId]) {
    return customPhotos[destinationId];
  }
  
  if (!destinationId) {
    return 'https://images.unsplash.com/photo-1488646953014-85cb44e25828?auto=format&fit=crop&w=800&q=80';
  }

  // Normalize key format
  const key = destinationId.startsWith('dest-') ? destinationId : `dest-${destinationId.toLowerCase()}`;
  
  // 2. Centralized registry photo
  if (destinationImages[key]) {
    return destinationImages[key];
  }
  
  // Check variations without prefix
  const simpleKey = destinationId.replace('dest-', '');
  if (destinationImages[`dest-${simpleKey}`]) {
    return destinationImages[`dest-${simpleKey}`];
  }

  // 3. Fallback
  return 'https://images.unsplash.com/photo-1488646953014-85cb44e25828?auto=format&fit=crop&w=800&q=80';
};
